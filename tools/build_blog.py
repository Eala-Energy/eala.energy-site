# ---------------------------------------------------------------- front matter

def _scalar(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in '"\'':
        v = v[1:-1].replace('\\"', '"') if v[0] == '"' else v[1:-1]
    return v


def parse_post(path):
    text = path.read_text(encoding='utf-8').replace('\r\n', '\n')
    if not text.startswith('---\n'):
        raise BuildError(f'{path.name}: must start with a "---" front matter block')
    end = text.find('\n---\n', 3)
    if end < 0:
        raise BuildError(f'{path.name}: front matter is not closed with "---"')
    meta, key = {}, None
    for line in text[4:end].split('\n'):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        item = re.match(r'^\s*-\s+(.*)$', line)
        if item and key:
            if not isinstance(meta[key], list):
                meta[key] = []
            meta[key].append(_scalar(item.group(1)))
            continue
        m = re.match(r'^([A-Za-z_]+):\s*(.*)$', line)
        if not m:
            raise BuildError(f'{path.name}: cannot parse front matter line: {line!r}')
        key, val = m.group(1), m.group(2).strip()
        if val.startswith('[') and val.endswith(']'):
            meta[key] = [_scalar(x) for x in val[1:-1].split(',') if x.strip()]
        else:
            meta[key] = _scalar(val)
    return meta, text[end + 5:].strip('\n')


def validate(path, meta, body):
    name, errs = path.name, []
    unknown = set(meta) - set(FIELDS_REQUIRED) - set(FIELDS_OPTIONAL)
    if unknown:
        errs.append(f'unknown field(s): {", ".join(sorted(unknown))}')
    for f in FIELDS_REQUIRED:
        if f not in meta or meta[f] in ('', None):
            errs.append(f'missing required field: {f}')
    for f in ('title', 'description', 'slug', 'date', 'updated', 'linkedin_url', 'image'):
        if f in meta and not isinstance(meta[f], str):
            errs.append(f'{f} must be a single value')
    if errs:
        raise BuildError(f'{name}: ' + '; '.join(errs))
    if not isinstance(meta['tags'], list):
        meta['tags'] = [meta['tags']]
    if len(meta['description']) > 155:
        errs.append(f'description is {len(meta["description"])} characters, max 155')
    if not SLUG_RE.match(meta['slug']):
        errs.append('slug must be lowercase latin letters, digits and single hyphens, e.g. "curtailment-in-2026"')
    for f in ('date', 'updated'):
        try:
            meta[f] = dt.date.fromisoformat(meta[f])
        except ValueError:
            errs.append(f'{f} must be YYYY-MM-DD')
    if not errs and meta['updated'] < meta['date']:
        errs.append('updated is earlier than date')
    url = meta.get('linkedin_url', '')
    if url and not re.match(r'^https://([a-z]+\.)?linkedin\.com/\S+$', url):
        errs.append('linkedin_url must be an https://www.linkedin.com/... URL')
    img = meta.get('image', '')
    if img and not re.match(r'^(https://\S+|/\S+)$', img):
        errs.append('image must be an https:// URL or a site path starting with /')
    if not body.strip():
        errs.append('article body is empty')
    if 'TODO' in body or any('TODO' in str(v) for v in meta.values()):
        errs.append('contains "TODO" (unfinished)')
    if errs:
        raise BuildError(f'{name}: ' + '; '.join(errs))
    meta['url'] = f'{SITE}/blog/{meta["slug"]}/'
    meta['image_url'] = (SITE + img if img.startswith('/') else img) if img else DEFAULT_IMAGE
    return meta


def load_posts():
    posts, errors = [], []
    for path in sorted(POSTS.glob('*.md')) if POSTS.is_dir() else []:
        if path.name.startswith('_'):
            continue
        try:
            meta, body = parse_post(path)
            meta = validate(path, meta, body)
            meta['html'] = markdown(body)
            meta['source'] = path.name
            posts.append(meta)
        except BuildError as e:
            errors.append(str(e))
    seen = {}
    for p in posts:
        if p['slug'] in seen:
            errors.append(f'{p["source"]}: slug "{p["slug"]}" already used by {seen[p["slug"]]}')
        seen[p['slug']] = p['source']
    if errors:
        raise BuildError('\n'.join(errors))
    return sorted(posts, key=lambda p: (p['date'], p['updated'], p['slug']), reverse=True)


# ---------------------------------------------------------------- markdown (documented subset, see BLOG.md)

def _attr(s):
    return s.replace('"', '&quot;')


def _safe_url(url):
    return url if re.match(r'^(https?://|mailto:|/|#)', url) else '#'


def _emph(s):
    s = re.sub(r'\*\*(?=\S)(.+?)(?<=\S)\*\*', r'<strong>\1</strong>', s)
    s = re.sub(r'(?<![\w*])\*(?=\S)(.+?)(?<=\S)\*(?![\w*])', r'<em>\1</em>', s)
    return re.sub(r'(?<![\w])_(?=\S)(.+?)(?<=\S)_(?!\w)', r'<em>\1</em>', s)


def inline(s):
    s = html.escape(s, quote=False)
    kept = []

    def keep(fragment):
        kept.append(fragment)
        return f'\x00{len(kept) - 1}\x00'

    s = re.sub(r'`([^`]+)`', lambda m: keep(f'<code>{m.group(1)}</code>'), s)
    s = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)\)', lambda m: keep(
        f'<img src="{_attr(_safe_url(m.group(2)))}" alt="{_attr(m.group(1))}" loading="lazy">'), s)
    s = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', lambda m: keep(
        f'<a href="{_attr(_safe_url(m.group(2)))}">{_emph(m.group(1))}</a>'), s)
    s = re.sub(r'&lt;(https?://[^\s&]+(?:&amp;[^\s&]+)*)&gt;', lambda m: keep(
        f'<a href="{_attr(m.group(1))}">{m.group(1)}</a>'), s)
    s = _emph(s)
    while '\x00' in s:
        s = re.sub(r'\x00(\d+)\x00', lambda m: kept[int(m.group(1))], s)
    return s


def _heading_id(text, used):
    plain = html.unescape(re.sub(r'<[^>]+>', '', text)).lower()
    base = re.sub(r'[^a-z0-9]+', '-', plain).strip('-') or 'section'
    hid, n = base, 2
    while hid in used:
        hid, n = f'{base}-{n}', n + 1
    used.add(hid)
    return hid


LIST_RE = re.compile(r'^(\s{0,3})([-*+]|\d+[.)])\s+(.*)$')
TABLE_SEP_RE = re.compile(r'^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$')


def _starts_block(line):
    return bool(re.match(r'^(#{1,6}\s|```|>|\s*([-*_])(\s*\2){2,}\s*$)', line) or LIST_RE.match(line))


def _cells(row):
    row = row.strip()
    row = row[1:] if row.startswith('|') else row
    row = row[:-1] if row.endswith('|') else row
    return [c.strip() for c in row.split('|')]


def markdown(md, used=None):
    used = set() if used is None else used
    lines, out, i = md.split('\n'), [], 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
        elif line.startswith('```'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('```'):
                j += 1
            out.append('<pre><code>' + html.escape('\n'.join(lines[i + 1:j]), quote=False) + '</code></pre>')
            i = j + 1
        elif m := re.match(r'^(#{1,6})\s+(.*?)\s*#*\s*$', line):
            level = min(max(len(m.group(1)), 2), 6)  # the page title is the only h1
            text = inline(m.group(2))
            out.append(f'<h{level} id="{_heading_id(text, used)}">{text}</h{level}>')
            i += 1
        elif re.match(r'^\s*([-*_])(\s*\1){2,}\s*$', line):
            out.append('<hr>')
            i += 1
        elif line.startswith('>'):
            j = i
            while j < len(lines) and lines[j].startswith('>'):
                j += 1
            inner = '\n'.join(re.sub(r'^> ?', '', x) for x in lines[i:j])
            out.append('<blockquote>' + markdown(inner, used) + '</blockquote>')
            i = j
        elif LIST_RE.match(line):
            ordered = LIST_RE.match(line).group(2)[0].isdigit()
            items = []
            while i < len(lines):
                m = LIST_RE.match(lines[i])
                if m and m.group(2)[0].isdigit() == ordered:
                    items.append(m.group(3))
                elif lines[i].strip() and lines[i].startswith((' ', '\t')) and items:
                    items[-1] += ' ' + lines[i].strip()
                elif not lines[i].strip() and i + 1 < len(lines) and LIST_RE.match(lines[i + 1]):
                    pass
                else:
                    break
                i += 1
            tag = 'ol' if ordered else 'ul'
            out.append(f'<{tag}>' + ''.join(f'<li>{inline(x)}</li>' for x in items) + f'</{tag}>')
        elif '|' in line and i + 1 < len(lines) and TABLE_SEP_RE.match(lines[i + 1]):
            head = _cells(line)
            rows, i = [], i + 2
            while i < len(lines) and '|' in lines[i] and lines[i].strip():
                rows.append(_cells(lines[i]))
                i += 1
            out.append('<div class="table-wrap"><table><thead><tr>'
                       + ''.join(f'<th>{inline(c)}</th>' for c in head) + '</tr></thead><tbody>'
                       + ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in rows)
                       + '</tbody></table></div>')
        else:
            j = i + 1
            while j < len(lines) and lines[j].strip() and not _starts_block(lines[j]):
                j += 1
            out.append('<p>' + inline(' '.join(x.strip() for x in lines[i:j])) + '</p>')
            i = j
    return '\n'.join(out)


