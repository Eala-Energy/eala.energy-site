def replace_marker(text, name, content, path):
    pat = re.compile(rf'(<!-- blog:{name} -->).*?(<!-- /blog:{name} -->)', re.S)
    if len(pat.findall(text)) != 1:
        raise BuildError(f'{path}: expected exactly one <!-- blog:{name} --> ... <!-- /blog:{name} --> marker pair')
    return pat.sub(lambda m: m.group(1) + content + m.group(2), text)


def update_home(text, has_posts):
    text = replace_marker(text, 'nav', '<a href="/blog/">Insights</a>' if has_posts else '', 'index.html')
    return replace_marker(text, 'footer', ' · <a href="/blog/">Insights</a>' if has_posts else '', 'index.html')


def update_sitemap(text, posts):
    text = re.sub(rf'\n  <url>\n    <loc>{re.escape(SITE)}/blog/.*?</url>', '', text, flags=re.S)
    if not posts:
        return text
    entries = [(f'{SITE}/blog/', max(p['updated'] for p in posts), 'weekly', '0.7')]
    entries += [(p['url'], p['updated'], 'yearly', '0.6') for p in posts]
    block = ''.join(f'''
  <url>
    <loc>{loc}</loc>
    <lastmod>{mod.isoformat()}</lastmod>
    <changefreq>{freq}</changefreq>
    <priority>{prio}</priority>
  </url>''' for loc, mod, freq, prio in entries)
    return text.replace('\n</urlset>', block + '\n</urlset>')


def update_llms(text, posts):
    text = re.sub(r'## Insights\n.*?(?=^## |\Z)', '', text, flags=re.S | re.M)
    if not posts:
        return text
    section = '## Insights\n\n' + f'- [All insights]({SITE}/blog/): {BLOG_DESC}\n' + ''.join(
        f'- [{p["title"]}]({p["url"]}): {p["description"]}\n' for p in posts) + '\n'
    if '## Contact' in text:
        return text.replace('## Contact', section + '## Contact', 1)
    return text.rstrip('\n') + '\n\n' + section.rstrip('\n') + '\n'


def desired_outputs(posts):
    """Map of path -> content for every file the generator owns or edits."""
    out = {}
    if posts:
        out[BLOG / 'index.html'] = render_index(posts)
        out[BLOG / 'feed.xml'] = render_feed(posts)
        for p in posts:
            out[BLOG / p['slug'] / 'index.html'] = render_post(p)
    for name, fn in (('index.html', lambda t: update_home(t, bool(posts))),
                     ('sitemap.xml', lambda t: update_sitemap(t, posts)),
                     ('llms.txt', lambda t: update_llms(t, posts))):
        path = ROOT / name
        out[path] = fn(path.read_text(encoding='utf-8'))
    return out


def stale_generated(out):
    """Generated blog files on disk that should no longer exist (e.g. a removed post)."""
    found = []
    for path in [BLOG / 'index.html', BLOG / 'feed.xml', *BLOG.glob('*/index.html')]:
        if path.is_file() and path not in out and MARK in path.read_text(encoding='utf-8'):
            found.append(path)
    return found


def new_post(title):
    slug = re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')
    if not slug:
        raise BuildError('cannot make a latin slug from that title; pass a title with latin letters')
    path = POSTS / f'{slug}.md'
    if path.exists():
        raise BuildError(f'{path.relative_to(ROOT)} already exists')
    today = dt.date.today().isoformat()
    safe_title = title.replace('"', "'")
    path.write_text(f'''---
title: "{safe_title}"
description: "TODO: one sentence, at most 155 characters"
date: {today}
updated: {today}
slug: {slug}
tags: []
# linkedin_url: https://www.linkedin.com/posts/...
---

TODO: write the article. Start sections with "## ". Cite sources as links.
''', encoding='utf-8')
    print(f'created {path.relative_to(ROOT)} — fill it in, then run: python3 tools/build_blog.py')


def main():
    ap = argparse.ArgumentParser(description='Build the eala.energy blog from blog/posts/*.md')
    ap.add_argument('--check', action='store_true', help='validate and verify generated files are up to date')
    ap.add_argument('--new', metavar='TITLE', help='create a new post file from the title')
    args = ap.parse_args()
    try:
        if args.new:
            return new_post(args.new)
        posts = load_posts()
        out = desired_outputs(posts)
        stale = stale_generated(out)
        changed = [p for p, c in out.items() if not p.exists() or p.read_text(encoding='utf-8') != c]
        rel = lambda p: str(p.relative_to(ROOT))
        if args.check:
            for p in changed:
                print(f'out of date: {rel(p)}')
            for p in stale:
                print(f'should be removed: {rel(p)}')
            if changed or stale:
                print('run: python3 tools/build_blog.py')
                return 1
            print(f'ok: {len(posts)} published post(s), generated files up to date')
            return 0
        for p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(out[p], encoding='utf-8')
            print(f'wrote {rel(p)}')
        for p in stale:
            p.unlink()
            print(f'removed {rel(p)}')
            if p.parent != BLOG and not any(p.parent.iterdir()):
                p.parent.rmdir()
        print(f'{len(posts)} published post(s)' + ('' if posts else ' — blog hidden (no links, no /blog/ pages)'))
        return 0
    except BuildError as err:
        print(f'error:\n{err}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
