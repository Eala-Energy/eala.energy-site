def render_post(p):
    tags = ''.join(f'<span class="tag">{e(t)}</span>' for t in p['tags'])
    updated = (f' · <span>Updated <time datetime="{p["updated"]}">{human(p["updated"])}</time></span>'
               if p['updated'] != p['date'] else '')
    discussion = (f'\n        <a href="{e(p["linkedin_url"])}" target="_blank" rel="noopener">Discussion on LinkedIn →</a>'
                  if p.get('linkedin_url') else '')
    dims = p['image_size']
    size_attrs = f' width="{dims[0]}" height="{dims[1]}"' if dims else ''
    caption = (f'<figcaption>{e(p["image_caption"])}</figcaption>' if p.get('image_caption') else '')
    cover = (f'\n      <figure class="cover"><img src="{e(p["image"])}" alt="{e(p["image_alt"])}"{size_attrs} '
             f'fetchpriority="high" decoding="async">{caption}</figure>' if p.get('image') else '')
